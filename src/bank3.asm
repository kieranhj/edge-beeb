INCBIN "src/data/compiled-nula.bin"
ENDIF
ELIF GFX_CPC
INCBIN "src/data/compiled-cpc.bin"
ELSE
INCBIN "src/data/compiled.bin"
ENDIF

\ ******************************************************************
\ *	The titles page's font and credits, and the code that draws them
\ ******************************************************************
\ *	Here rather than in bank 0 because bank 0 has 358 bytes left and
\ *	this is 702 of data, and because the page is drawn once: paging
\ *	this bank in for it costs nothing. tools/export_title.py.
\ *
\ *	The font is the C64's own status charset read as MULTICOLOUR, which
\ *	is what it is: four double-width pixels a character, which is one
\ *	of our 4-fat-pixel cells exactly, so the original's 38-column
\ *	layout lands at 1:1 with no rescaling.
\ *
\ *	CALLED THROUGH bank3_call IN MAIN RAM, which does the paging.
\ *	Nothing in this bank can page its own bank out.
\ ******************************************************************

\ TITLE_GLYPH_BYTES, TITLE_LINE_LEN and TITLE_LINES are in main.asm now:
\ src/panel.asm needs them too, and it is assembled before this file.

.title_font
INCBIN "src/data/title.bin"
title_lines_data = title_font + 32 * TITLE_GLYPH_BYTES

\ The C64 puts its five lines on screen rows 12, 14, 15, 16 and 17 of 25.
\ Its status bar is five rows and so is ours, so its rows 5-24 are our play
\ rows 0-19 and the page transcribes 1:1 - the lines land on play rows 7, 9,
\ 10, 11 and 12. Layer 6c had them a row lower, re-centred, because there
\ was nothing else on the page; with the zoom bands in, the original's own
\ spacing is what fits.
\
\ Layer 9e draws this block twice over, from two sets of five lines: bank 3's
\ own, below, and this port's at TTL_EXTRA, which rides on the end of the
\ PANEL file. ttl_cred_ptr in main RAM says which, and is the only change the
\ crossfade needed here - the fade itself is the palette (decision 53).
\
\ These are rows of the CREDITS BLOCK, not of the play area: cycle C starts
\ at TTL_CRED and play row 7 is its row 0.
.title_rows EQUB 0, 2, 3, 4, 5

\ 38 characters is 152 of the 160 pixels, so one byte column of margin.
TITLE_COL0 = 2

\ The zero page it borrows: write_ptr and read_ptr are the generic pair, and
\ spr_tmp is the sprite engine's scratch. Nothing is drawing sprites while the
\ titles are up, and clear_play has finished with write_ptr before this runs.
.title_text
{
    ldx #0                      \\ line
    .line_loop
    stx line_no

    \\ write_ptr = screen_start + row * 640 + TITLE_COL0 * 8
    ldy title_rows, x
    lda #LO(screen_start + TITLE_COL0 * 8)
    sta write_ptr
    lda #HI(screen_start + TITLE_COL0 * 8)
    sta write_ptr+1
    .row_loop
    cpy #0
    beq row_done
    clc
    lda write_ptr   : adc #LO(row_stride) : sta write_ptr
    lda write_ptr+1 : adc #HI(row_stride) : sta write_ptr+1
    dey
    bne row_loop
    .row_done

    \\ read_ptr = this line's 38 glyph numbers. Four lines at 38 is 152,
    \\ so the multiply stays inside a byte.
    ldy #0
    .times_loop
    cpx #0
    beq times_done
    tya : clc : adc #TITLE_LINE_LEN : tay
    dex
    bne times_loop
    .times_done
    tya
    clc
    adc ttl_cred_ptr : sta read_ptr        ; WHICH SET: bank 3's own copy of
    lda #0                                 ; the C64's, or this port's at
    adc ttl_cred_ptr+1 : sta read_ptr+1    ; TTL_EXTRA (decision 53)

    ldx #0
    .char_loop
    stx char_no

    \\ spr_tmp = title_font + glyph * 16. Thirty-two glyphs reach 496, so
    \\ the shift is a 16-bit one - a single ROL would lose the top bits.
    ldy #0
    lda (read_ptr), y
    sta spr_tmp
    lda #0
    sta spr_tmp+1
    ldx #4
    .shift
    asl spr_tmp
    rol spr_tmp+1
    dex
    bne shift
    clc
    lda spr_tmp   : adc #LO(title_font) : sta spr_tmp
    lda spr_tmp+1 : adc #HI(title_font) : sta spr_tmp+1

    \\ A glyph is two byte columns, and our byte columns are 8 bytes apart
    \\ and consecutive, so it is one straight 16-byte copy.
    ldy #TITLE_GLYPH_BYTES-1
    .copy
    lda (spr_tmp), y
    sta (write_ptr), y
    dey
    bpl copy

    clc
    lda write_ptr : adc #TITLE_GLYPH_BYTES : sta write_ptr
    bcc no_carry
    inc write_ptr+1
    .no_carry
    inc read_ptr
    bne no_carry2
    inc read_ptr+1
    .no_carry2

    ldx char_no
    inx
    cpx #TITLE_LINE_LEN
    bne char_loop

    ldx line_no
    inx
    cpx #TITLE_LINES
    beq done
    jmp line_loop
    .done
    rts

    .line_no EQUB 0
    .char_no EQUB 0
}

\ ******************************************************************
\ *	The memorial's page - "IN MEMORY OF T.M.R." (Layer 9d)
\ ******************************************************************
\ *	Jason "T.M.R." Kelk wrote Edge Grinder, and his name is already
\ *	in the credits above. Between the loading picture and the titles
\ *	the picture fades out, this goes up in the credits' own font, and
\ *	it fades out again. Decision 52.
\ *
\ *	Only the half that needs the font is here: the fade, the field
\ *	timing and the sequencing are in main RAM, because the CPC build's
\ *	bank 3 has 162 bytes below the tune and the whole thing is 275.
\ *	This half is one call - clear the picture, draw the message -
\ *	made with the palette already black, so neither is ever seen
\ *	happening. `memorial` in src/main.asm is the other half.
\ *
\ *	The caller has set &FE34 so the CPU sees MAIN, which is the bank
\ *	the loading picture is displayed from, and holds interrupts off.
\ ******************************************************************

\ The message in the credits' own glyph numbers: 0 blank, 1-26 A-Z,
\ &1c full stop. Nineteen characters of the forty across the screen, so
\ column 10 centres it bar half a character, and row 15 of 32 puts it
\ half a row above the middle.
MEM_LEN = 19
MEM_ROW = 15
MEM_COL = 10
MEM_ADDR = LOADSCR_ADDR + MEM_ROW * row_stride + MEM_COL * TITLE_GLYPH_BYTES

.mem_text
EQUB  9, 14,  0                 ; I N
EQUB 13,  5, 13, 15, 18, 25,  0 ; M E M O R Y
EQUB 15,  6,  0                 ; O F
EQUB 20, &1c, 13, &1c, 18, &1c  ; T . M . R .

.mem_page
{
    \ The picture goes: 20K at &3000, under a black palette.
    lda #0
    sta write_ptr
    lda #HI(LOADSCR_ADDR)
    sta write_ptr+1
    lda #0
    ldx #(&8000 - LOADSCR_ADDR) DIV 256
    ldy #0
    .pages
    .bytes
    sta (write_ptr), y
    iny
    bne bytes
    inc write_ptr+1
    dex
    bne pages

    \ And the message takes its place.
    lda #LO(MEM_ADDR) : sta write_ptr
    lda #HI(MEM_ADDR) : sta write_ptr+1

    ldx #0
    .char_loop
    stx md_ch

    \ spr_tmp = title_font + glyph * 16, sixteen bits: glyph &1c
    \ reaches 448 and a single ROL would lose it.
    lda mem_text, x
    sta spr_tmp
    lda #0
    sta spr_tmp+1
    ldx #4
    .shift
    asl spr_tmp
    rol spr_tmp+1
    dex
    bne shift
    clc
    lda spr_tmp   : adc #LO(title_font) : sta spr_tmp
    lda spr_tmp+1 : adc #HI(title_font) : sta spr_tmp+1

    \ Two byte columns, eight bytes apart and consecutive: one copy.
    ldy #TITLE_GLYPH_BYTES-1
    .copy
    lda (spr_tmp), y
    sta (write_ptr), y
    dey
    bpl copy

    clc
    lda write_ptr : adc #TITLE_GLYPH_BYTES : sta write_ptr
    bcc no_carry
    inc write_ptr+1
    .no_carry

    ldx md_ch
    inx
    cpx #MEM_LEN
    bne char_loop
    rts

    .md_ch EQUB 0
}

\ ******************************************************************
\ *	The status panel and the HUD (Layer 6d)
\ ******************************************************************
\ *	The C64's status bar is five rows of 40 characters assembled
\ *	straight into its screen buffer and never redrawn; only the score,
\ *	the high score and the lives bars move, and status_decode pokes
\ *	those characters back. tools/export_panel.py renders the whole
\ *	thing to MODE 2 once, at 1:1 - the charset is multicolour, so a
\ *	character is four double-width pixels, which is one of our
\ *	4-fat-pixel cells (decision 34 for the colour mapping).
\ *
\ *	Under GFX_CPC the glyphs are the Amstrad port's game font and its
\ *	life marker (decision 56). The CPC port copied the C64's panel
\ *	layout to the column, blank border columns included, so every
\ *	address below is the same in both builds - only the INCBIN moves.
\ *
\ *	The image itself is no longer here - it is a disc file, unpacked
\ *	straight into each bank's screen at boot (decision 47). What is
\ *	left is the HUD: its glyphs, its cell addresses, and the cache of
\ *	what each bank is showing. Reached through bank3_call in main RAM.
\ ******************************************************************

HUD_GLYPH_BYTES = 16
HUD_CELLS = 18                  ; 6 score + 6 high score + 6 lives

.hud_glyphs
IF GFX_NULA
IF GFX_CPC
INCBIN "src/data/hud-nula-cpc.bin"       \ the Amstrad port's own font, decision 56
ELSE
INCBIN "src/data/hud-nula.bin"       \ the Amstrad port's own font, decision 56
ENDIF
ELIF GFX_CPC
INCBIN "src/data/hud-cpc.bin"       \ the Amstrad port's own font, decision 56
ELSE
INCBIN "src/data/hud.bin"       \ the Amstrad port's own font, decision 56
ENDIF

\ The C64's status_decode writes the score to buffer_1+$02e, the high score
\ to +$042 and the lives bars to +$060: row 1 columns 6 and 26, row 2 column
\ 16. A cell is SIXTEEN bytes - four fat pixels is two byte columns, and a
\ byte column is eight - so it sits at PANEL_ADDR + row*640 + column*16, and
\ 40 of them is the 640-byte row exactly.
\ HUD_COL_SHIFT is export_panel.py's PANEL_SHIFT: the exporter rotates the
\ panel one column right to centre it, because the C64's 38-column border ate
\ the two blank columns at the end and ours does not. These cells move with it.
HUD_COL_SHIFT = 1

.hud_cell_lo
FOR c, 6 + HUD_COL_SHIFT, 11 + HUD_COL_SHIFT, 1
    EQUB LO(PANEL_ADDR + 1*row_stride + c*HUD_GLYPH_BYTES)
NEXT
FOR c, 26 + HUD_COL_SHIFT, 31 + HUD_COL_SHIFT, 1
    EQUB LO(PANEL_ADDR + 1*row_stride + c*HUD_GLYPH_BYTES)
NEXT
FOR c, 16 + HUD_COL_SHIFT, 21 + HUD_COL_SHIFT, 1
    EQUB LO(PANEL_ADDR + 2*row_stride + c*HUD_GLYPH_BYTES)
NEXT

.hud_cell_hi
FOR c, 6 + HUD_COL_SHIFT, 11 + HUD_COL_SHIFT, 1
    EQUB HI(PANEL_ADDR + 1*row_stride + c*HUD_GLYPH_BYTES)
NEXT
FOR c, 26 + HUD_COL_SHIFT, 31 + HUD_COL_SHIFT, 1
    EQUB HI(PANEL_ADDR + 1*row_stride + c*HUD_GLYPH_BYTES)
NEXT
FOR c, 16 + HUD_COL_SHIFT, 21 + HUD_COL_SHIFT, 1
    EQUB HI(PANEL_ADDR + 2*row_stride + c*HUD_GLYPH_BYTES)
NEXT

\ The C64's lives_display, as glyph indices: $00 -> 0, $8f -> 11, $90 -> 12.
\ Its rows are eight bytes and it uses six of them; ours are six.
.hud_lives
    EQUB  0,  0,  0,  0,  0,  0     ; no lives left
    EQUB  0,  0, 11, 12,  0,  0
    EQUB  0, 11, 12, 11, 12,  0
    EQUB 11, 12, 11, 12, 11, 12
.hud_lives_off EQUB 0, 6, 12, 18

\ What the panel should show, and what each bank's panel is already
\ showing. A bank is redrawn every other game frame, so the two are
\ tracked apart, exactly as the sprite engine tracks its save state:
\ a change writes into the bank the CPU owns now and again next frame.
.hud_want SKIP HUD_CELLS
.hud_have SKIP 2 * HUD_CELLS

\ ******************************************************************
\ *	panel_dirty - forget what both banks' panels are showing
\ ******************************************************************
\ *	panel_init in bank 0 has just unpacked the panel image over one
\ *	bank's &3000, so nothing of the HUD survives in it. The image
\ *	itself used to be here too, 3,200 bytes of boot-time data holding
\ *	ground the tune needs (decision 47); it is a disc file now and all
\ *	that is left in bank 3 is this, beside the cache it invalidates.
\ ******************************************************************

.panel_dirty
{
    ldx #2*HUD_CELLS-1
    lda #&ff
    .dirty
    sta hud_have, x
    dex
    bpl dirty
    rts
}

.status_decode
{
    \\ ---- what the panel should show -------------------------------
    ldx lives
    cpx #4
    bcc lives_ok
    ldx #3                      ; never happens; costs four cycles to be sure
    .lives_ok
    ldy hud_lives_off, x

    ldx #0
    .want_loop
    lda score, x
    clc
    adc #1                      ; glyph 1 is '0'; the C64 adds $21 for the same
    sta hud_want, x
    lda hi_score, x
    clc
    adc #1
    sta hud_want + 6, x
    lda hud_lives, y
    sta hud_want + 12, x
    iny
    inx
    cpx #SCORE_DIGITS
    bne want_loop

    \\ ---- and what this bank is showing ----------------------------
    lda &fe34
    and #4                      ; X bit: the bank the CPU writes
    beq main_bank
    lda #HUD_CELLS
    .main_bank
    sta bank_off

    ldx #0
    .cell_loop
    txa
    clc
    adc bank_off
    tay
    lda hud_want, x
    cmp hud_have, y
    beq next_cell
    sta hud_have, y

    \\ read_ptr = hud_glyphs + glyph * 16. Thirteen glyphs reach 192, so
    \\ the shift stays inside a byte.
    asl a : asl a : asl a : asl a
    clc
    adc #LO(hud_glyphs) : sta read_ptr
    lda #0
    adc #HI(hud_glyphs) : sta read_ptr+1

    lda hud_cell_lo, x : sta write_ptr
    lda hud_cell_hi, x : sta write_ptr+1

    ldy #HUD_GLYPH_BYTES-1
    .copy
    lda (read_ptr), y
    sta (write_ptr), y
    dey
    bpl copy

    .next_cell
    inx
    cpx #HUD_CELLS
    bne cell_loop
    rts

    .bank_off EQUB 0
}

\ ******************************************************************
\ *	music_init - start the tune (Layer 7)
\ *
\ *	Here rather than in bank 0 because it began as the one thing that
\ *	had to read the .vgi header out of music_lo, in THIS bank. Under
\ *	VGI_SPLIT there is no header - vgm_stream_mount takes eleven
\ *	addresses from the map instead - so it could go anywhere now; it
\ *	stays because bank 3 has the room and bank 0 has not. Reached from
\ *	boot through bank3_call, which has already done the paging; all
\ *	this adds is HAZEL, where the player's code is, and that does not
\ *	page bank 3 out because it is a different window.
\ *
\ *	C = 1 is the player's "loop for ever", which is what the C64 does
\ *	with its own tune.
\ ******************************************************************

.music_init
{
    lda &fe34
    ora #HAZEL_BIT
    sta &fe34
IF MUSIC_AKL
    lda #LO(MUSIC_AKL_SONG)     ; the Arkos replay: song address, subsong 0
    ldx #HI(MUSIC_AKL_SONG)
    ldy #0
    jsr akl_init
ELSE
    lda #HI(HAZEL_WORK)         ; VGI_SPLIT: X/Y unused, the map says where
    sec                         ; C=1: loop for ever, as the C64 does
    jsr vgm_init
ENDIF
    lda &fe34
    and #255-HAZEL_BIT
    sta &fe34
    rts
}

