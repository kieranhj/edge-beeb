\ ******************************************************************
\ *	Layer 9h's two leaf routines, up here in the tail
\ ******************************************************************
\ *	They belong with the rest of the redefine screen and they are
\ *	here because the hole below the tune could not hold all of it:
\ *	the code came in 69 bytes over, the tables went to &3C80 and
\ *	these 55 bytes came here. The two halves of this bank are one
\ *	bank - only the tune stream at MUSIC_B1_BASE is between them -
\ *	so a jsr from the hole reaches them with nothing paged.
\ ******************************************************************

\ ---- kr_blank: the six rows wiped, row 1 included -----------------
\ THE CREDITS CANNOT CLEAR ROW 1. Their own row list is the C64's spacing -
\ 0, 2, 3, 4, 5, with a gap - so title_text never writes credit row 1 at
\ all, and the redefine screen's second line sat there behind them: LEFT on
\ the left and its binding on the right, over the top of the credits.
\ Caught in jsbeeb the moment ESCAPE first worked.
\ So the way out paints the whole six blank before the credits go back over
\ five of them. It costs a second full paint, which is two fields on a page
\ that is about to change anyway.
.kr_blank
{
    lda #0
    ldx #TITLE_LINE_LEN * KR_LINES
    .clr
    dex
    sta kr_block, x
    bne clr
    jmp kr_paint                ; its rts
}

\ ---- kr_copy: one fixed-width field into the block ----------------
\ Y = the source glyph in kr_text (main RAM, at &3C80 behind the credits),
\ X = the destination in kr_block (main RAM, in the &0800 block), kr_cnt =
\ how many. Both tables are read and written from this bank with nothing
\ paged: a sideways bank reads and writes main RAM freely.
.kr_copy
{
    .loop
    lda kr_text, y
    sta kr_block, x
    iny
    inx
    dec kr_cnt
    bne loop
    rts
}

\ ---- kr_showkey: name the key at kr_dst --------------------------
\ A = an internal key number. A letter is one glyph - its index in kr_keys
\ plus one, the font being blank, A-Z, then ! . , - ? - and the other eight
\ are an 8-glyph name record, which follows the five labels in kr_text. A
\ number that is not a candidate at all leaves the field blank rather than
\ drawing a wild glyph; nothing can currently produce one, the five defaults
\ all being letters, but a future default that was not would be silent.
.kr_showkey
{
    ldy #KR_CANDS-1
    .find
    cmp kr_keys, y
    beq got
    dey
    bpl find
    rts
    .got
    cpy #KR_LETTERS
    bcs named
    iny
    tya
    ldx kr_dst
    sta kr_block, x
    rts
    .named
    tya
    sec
    sbc #KR_LETTERS - KR_LABELS
    asl a : asl a : asl a       ; * KR_REC
    tay
    ldx kr_dst
    lda #KR_REC : sta kr_cnt
    jmp kr_copy                 ; its rts
}

\ ******************************************************************
\ *	Layer 9c: the parallax starfield
\ ******************************************************************
\ *	Ten stars on scanline 0 of every other character row, drifting
\ *	left more slowly than the level does, at two speeds. Five go at
\ *	half the scroll and five at a quarter, and the two sets alternate
\ *	rows, so the play area reads as three planes: the scenery in
\ *	front, then the cyan stars, then the green.
\ *
\ *	THE TEN, AND THE RULES, ARE THE CPC PORT'S, NOT THE C64'S. The
\ *	original animates a single pixel in row 0 of character $FF
\ *	(`star_decode`, `sta $47f8` in rout2) - and character $FF is in
\ *	neither `tiles.til` nor the map, so nothing ever displays it. The
\ *	only $FF on its screen is the status bar's last row, whose colour
\ *	RAM is $00: black on black. The C64's starfield is dead code.
\ *	Axelay's CPC port wrote a real one
\ *	(source_cpc/Source/EG_Stars3.asm) and this is that: its ten
\ *	positions, its two colours, and its two rules.
\ *
\ *	THE TWO RULES ARE WHAT MAKE IT CHEAP. A star is plotted only into
\ *	a byte that is blank, so it never covers the scenery and never has
\ *	to remember what it covered; and it is wiped by writing that blank
\ *	back. So the only thing worth remembering is WHERE, which is
\ *	star_lo/star_hi - per bank, because a bank is redrawn every other
\ *	frame and what has to be put back is wherever that bank last left
\ *	it. A zero high byte means this bank did not plot this star at
\ *	all, and no address in a play buffer has one.
\ *
\ *	THE DRIFT IS OURS (decision 51). The CPC's stars stand still on
\ *	the screen; ours step one fat pixel left on their own beat, which
\ *	is `frame_count AND star_mask`. The level moves one fat pixel a
\ *	frame, so mask 1 is half its speed and mask 3 a quarter, and
\ *	everything is slower than the scenery - which is the whole point:
\ *	nearer things move faster, so a star that moves at all has to
\ *	move less than the level in front of it.
\ *
\ *	A step is half a byte. Moving left out of the LEFT half of a byte
\ *	lands in the RIGHT half of the byte before it, so the pixel goes
\ *	down a shift and the column goes back one; moving left out of the
\ *	right half lands in the left half of the same byte, so only the
\ *	pixel moves. MODE 2 puts the left pixel's four bits at 7,5,3,1 and
\ *	the right pixel's at 6,4,2,0, so the two forms are one ASL apart
\ *	and `AND #&55` tells them apart.
\ *
\ *	WHY IT NEEDS NO ADDRESS OF ITS OWN. The CPC increments each star's
\ *	screen address every frame to cancel the scroll. We do not have
\ *	to: `corner_addr` already is that address. A star is a sprite that
\ *	never moves except when we move it, and `sprite.asm` places one at
\ *	`corner_addr + 8 + row * 640 + column * 8`; `scroll_advance`
\ *	running AFTER the draw is what makes a stationary sprite
\ *	stationary (BUGS.md #7). So star_ofs is a screen offset, the same
\ *	in both banks, and the drift is the only thing that changes it.
\ *
\ *	The two banks hold the same picture one pixel apart, so a star at
\ *	the same byte and the same half-byte in both is at the same screen
\ *	pixel in both, and does not shimmer. Only the blank test can
\ *	disagree between them, at the edge of a piece of scenery.
\ *
\ *	A star may stand in the incoming column, 79, and one will: they
\ *	visit every column now. That is safe only because `scroll_frame`
\ *	runs BEFORE this does, so the star goes on top of a column that
\ *	has just been written, and by the time this bank comes round again
\ *	the scroll has moved on and nothing has repainted it.
\ *
\ *	NOT PORTED: the CPC swaps its two colours over every second frame,
\ *	to hide a half-character R3 shift on monitors that do not do it
\ *	cleanly. We have no R3 and no shift, and at 25 Hz the swap would
\ *	be a visible flicker rather than a disguise.
\ *
\ *	Here in bank 1 because main RAM has 185 bytes and this is more
\ *	than half of them, and because the 247 bytes between the zoom
\ *	scroller and the tune's B1 stream at &B900 were dead space.
\ *	Reached through bank_call, like the zoom scroller above it. It
\ *	reads `corner_addr` and `frame_count` in zero page and writes the
\ *	play buffer, none of which is paged, so being up here costs it
\ *	nothing but the call.
\ ******************************************************************

\ ******************************************************************
\ *	star_init - back to the CPC's positions, nothing on screen
\ ******************************************************************
.star_init
{
    ldx #STAR_COUNT-1
    .loop
    lda star_ofs0_lo, x
    sta star_ofs_lo, x
    lda star_ofs0_hi, x
    sta star_ofs_hi, x
    lda star_col0, x
    sta star_col, x
    lda star_pix0, x
    sta star_pix, x
    dex
    bpl loop

    lda #0
    ldx #STAR_BANK + STAR_COUNT - 1
    .clear
    sta star_hi, x              ; star_lo needs no clearing: this gates it
    dex
    bpl clear
    rts
}

\ ******************************************************************
\ *	star_frame - put last time's stars back, drift, plot this time's
\ ******************************************************************
\ *	X walks the star and Y the same star in the bank being drawn,
\ *	which is why the screen byte is reached through self-modified
\ *	absolute addresses rather than (zp),Y: it leaves both index
\ *	registers to the loop.
\ ******************************************************************

.star_frame
{
    lda &fe34
    and #4                      ; the X bit: the bank the CPU is drawing
    asl a
    asl a                       ; 0 for main, STAR_BANK for shadow
    clc
    adc #STAR_COUNT-1
    tay
    ldx #STAR_COUNT-1

    .loop

    \\ ---- put the blank back where this bank last drew this star ---
    lda star_hi, y
    beq not_drawn
    sta wipe+2
    lda star_lo, y
    sta wipe+1
    lda #0
    sta star_hi, y
    .wipe
    sta &ffff
    .not_drawn

    \\ ---- drift one fat pixel left, on this star's own beat --------
    lda frame_count
    and star_mask, x
    bne no_step

    lda star_pix, x
    and #&55                    ; bits in the right-hand pixel?
    bne to_left

    \\ Out of the left half of this byte, into the right half of the
    \\ one before it: down a shift, and back a column.
    lsr star_pix, x
    dec star_col, x
    bpl back_one
    lda #PLAY_COLS-1            ; off the left edge and on again at the right
    sta star_col, x
    clc
    lda star_ofs_lo, x
    adc #LO(PLAY_COLS * 8 - 8)
    sta star_ofs_lo, x
    lda star_ofs_hi, x
    adc #HI(PLAY_COLS * 8 - 8)
    sta star_ofs_hi, x
    jmp no_step

    .back_one
    sec
    lda star_ofs_lo, x
    sbc #8
    sta star_ofs_lo, x
    lda star_ofs_hi, x
    sbc #0
    sta star_ofs_hi, x
    jmp no_step

    \\ Out of the right half into the left half of the same byte: the
    \\ pixel moves and the column does not.
    .to_left
    asl star_pix, x

    .no_step

    \\ ---- where it is now, in the bank being drawn -----------------
    \\ The buffer is 16K and hardware-wrapped, and corner_addr plus an
    \\ offset can only pass &8000 once, so one subtraction puts it back.
    clc
    lda corner_addr
    adc star_ofs_lo, x
    sta test+1
    sta plot+1
    lda corner_addr+1
    adc star_ofs_hi, x
    cmp #HI(screen_top)
    bcc in_range
    sbc #HI(screen_size)
    .in_range
    sta test+2
    sta plot+2

    \\ ---- plot, but only into scenery that is not there ------------
    .test
    lda &ffff
    bne blocked
    lda star_pix, x
    .plot
    sta &ffff
    lda plot+1                  ; and remember it, for this bank's next wipe
    sta star_lo, y
    lda plot+2
    sta star_hi, y
    .blocked

    dey
    dex
    bmi done                    \ the body is past a branch's reach from the top
    jmp loop
    .done
    rts
}

\ ******************************************************************
\ *	Layer 9c: the completion sequence's "MEGA HERO" message
\ ******************************************************************
\ *	The C64's comp_mess draws it a cell a field over the frozen play
\ *	area: character $80 in light green wherever mega_hero_txt holds
\ *	$20 - six rows of forty at screen row 8, and the same again at row
\ *	16 revealed from its LAST cell backwards, so the two blocks meet
\ *	in the middle. It is not a font and never needed one: it is two
\ *	240-cell on/off bitmaps and one repeated character, which is what
\ *	docs/layer-6c-state-machine.md corrected on 2026-09-04.
\ *
\ *	A C64 character is four multicolour pixels, so it is four of our
\ *	fat pixels, so forty of them are our whole 160-pixel width and one
\ *	cell is 16 bytes - the zoom scroller's cell exactly, and copied the
\ *	same way. tools/export_mega.py converts the character and both
\ *	bitmaps; the second is stored back to front, so one ASL a step
\ *	serves a block that reveals forwards and a block that reveals back.
\ *
\ *	THE SHADOW IS THE ORIGINAL'S. Beside every cell it draws, the C64
\ *	blanks the cell 41 on - one row down and one to the right - which
\ *	punches the scenery out behind the letters and leaves them a drop
\ *	shadow. Block 1 runs forwards, so the cell it blanks cannot have
\ *	been drawn yet and needs no test; block 2 runs backwards, so the
\ *	cell it blanks may already carry a letter, and the original reads
\ *	the screen to find out before it blanks. Both transcribe.
\ *
\ *	IT BLOCKS, and the whole loop is up here, because comp_mess in
\ *	bank 0 has twenty-five bytes left and this is two hundred. Nothing
\ *	in a sideways bank may call main RAM - but field_wait is three
\ *	instructions over a main-RAM variable and inlines, and for the five
\ *	seconds this takes nothing runs but the music interrupt.
\ *
\ *	BOTH BANKS, every cell. field_wait hands no frame over, so the
\ *	display stands still on one bank while this runs - but the finale
\ *	after it flips again, and a message in one bank only would strobe
\ *	at 25 Hz from the moment it did.
\ ******************************************************************


\ ******************************************************************
\ *	mega_mess - the message, a cell a field, and then return
\ ******************************************************************

.mega_mess
{
    lda #LO(MEGA_O1) : sta mega_o
    lda #HI(MEGA_O1) : sta mega_o+1
    lda #LO(MEGA_O2) : sta mega_o+2
    lda #HI(MEGA_O2) : sta mega_o+3
    lda #0
    sta mega_j

    .group
    ldx mega_j
    lda mega_bits1, x
    sta mega_m
    lda mega_bits2, x
    sta mega_m+2
    inc mega_j
    lda #8
    sta mega_n

    .cell
    \ field_wait, inlined: it is a read of a main-RAM variable and
    \ nothing more, and this bank cannot call the routine itself.
    lda field_count
    .same
    cmp field_count
    beq same

    lda #0
    jsr mega_one
    lda #2
    jsr mega_one

    clc                         ; block 1 forwards, block 2 backwards
    lda mega_o   : adc #TTL_CELL : sta mega_o
    lda mega_o+1 : adc #0        : sta mega_o+1
    sec
    lda mega_o+2 : sbc #TTL_CELL : sta mega_o+2
    lda mega_o+3 : sbc #0        : sta mega_o+3

    dec mega_n
    bne cell
    lda mega_j
    cmp #MEGA_CELLS / 8
    bne group
    rts
}


\ ******************************************************************
\ *	mega_plot - one cell into BOTH banks
\ ******************************************************************
\ *	mega_ofs is the offset from corner_addr, mega_src the sixteen
\ *	bytes to put there, and mega_guard says whether a cell already
\ *	carrying a letter is to be left alone. Two byte columns of eight
\ *	rather than one run of sixteen: the buffer wraps at 16K and a
\ *	sixteen-byte run can straddle the wrap, but an eight-byte column
\ *	starting on an eight-byte boundary cannot.
\ ******************************************************************

.mega_plot
{
    lda &fe34
    pha
    and #255 - 4                ; the CPU sees MAIN
    jsr pass
    lda &fe34
    ora #4                      ; and then SHADOW
    jsr pass
    pla
    sta &fe34
    rts

    .pass
    sta &fe34
    ldx #0
    jsr ptrs
    lda mega_guard
    beq columns
    ldy mega_key
    lda (write_ptr), y
    cmp mega_block, y
    beq out                     ; a letter is there already: leave it alone
    .columns
    jsr copy8
    ldx #8
    jsr ptrs
    jsr copy8
    .out
    rts

    \ X = the byte column within the cell, 0 or 8.
    .ptrs
    clc
    lda corner_addr
    adc mega_ofs
    sta write_ptr
    lda corner_addr+1
    adc mega_ofs+1
    sta write_ptr+1
    txa
    clc
    adc write_ptr
    sta write_ptr
    bcc no_carry
    inc write_ptr+1
    .no_carry
    lda write_ptr+1
    cmp #HI(screen_top)
    bcc in_range
    sbc #HI(screen_size)
    sta write_ptr+1
    .in_range
    txa
    clc
    adc mega_src
    sta read_ptr
    lda mega_src+1
    adc #0
    sta read_ptr+1
    rts

    .copy8
    ldy #7
    .cl
    lda (read_ptr), y
    sta (write_ptr), y
    dey
    bpl cl
    rts
}


